_QA_RE = re.compile(r"Q[：:]\s*(.+?)\s*\n\s*A[：:]\s*(.+?)(?=\n\s*Q[：:]|\Z)", re.S)


def extract_pairs(conn) -> list[tuple[str, str, str]]:
    """(question, answer, doc_id)；只取 active 文档，答案过短/问题过短剔除。"""
    rows: list[tuple[str, str, str]] = []
    with conn:
        with conn.cursor() as cur:
            cur.execute(
                "SELECT c.doc_id, c.content FROM chunk_store c "
                "JOIN doc_registry d ON d.doc_id = c.doc_id AND d.status = 'active' "
                "WHERE c.content LIKE %s",
                ("%Q：%",),
            )
            for doc_id, content in cur.fetchall():
                for m in _QA_RE.finditer(content or ""):
                    q = re.sub(r"\s+", " ", m.group(1)).strip()
                    a = re.sub(r"\s+", " ", m.group(2)).strip()
                    if len(q) >= 4 and len(a) >= 4:
                        rows.append((q, a, doc_id))
    return rows


