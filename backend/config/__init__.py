# 本门用 Redis sorted set 槽位补全局口径。分层语义：本门=硬上限无等待队列
# （满即 503+Retry-After），排队/优先级仍由进程内门承担；Redis 不可用
# fail-open 放行（进程内门兜底）。默认 false——关闭时零 Redis 访问、行为与主线一致。
