# 低优先级（上传/重索引/导出）几乎不等待直接拒绝。0 表示禁用排队（恢复纯 503）。
CONCURRENCY_QUEUE_TIMEOUT = float(os.getenv("CONCURRENCY_QUEUE_TIMEOUT", "10"))

